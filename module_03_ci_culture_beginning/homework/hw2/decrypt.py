import sys

# Импортируем модуль sys, чтобы читать данные из стандартного ввода (sys.stdin).
# Это позволяет программе работать как консольная утилита: она получает входной текст,
# обрабатывает его и выводит результат обратно в консоль.


def decrypt(encryption: str) -> str:
    """
    Функция decrypt выполняет «расшифровку» строки по специальному правилу с точками.

    Логика:
    - Проходим по всем символам входной строки encryption.
    - Если очередной символ не точка, добавляем его в результат и обнуляем счётчик точек.
    - Если символ — точка, увеличиваем счётчик dots.
      * Когда dots == 2 (то есть встретилась пара подряд идущих точек "..") и в результате есть символы,
        удаляем последний добавленный символ из result.
        После удаления сбрасываем dots в 0.
    - Одиночные точки сами по себе ничего не удаляют, но участвуют в подсчёте подряд идущих точек.
    - Длинные последовательности точек по две удаляют предыдущие символы; если символы закончились,
      дальнейшие пары точек уже не влияют на результат.

    В итоге:
    - Каждая пара точек ".." работает как «Backspace» для одного предыдущего символа.
    - Функция возвращает итоговую строку, собранную из списка result.
    """
    result: list = []  # сюда по одному добавляются символы расшифрованной строки
    dots: int = 0      # счётчик подряд идущих точек

    for symbol in encryption:
        # Если текущий символ НЕ точка, просто добавляем его в результат.
        if symbol != '.':
            result.append(symbol)
            # Сброс счётчика точек, так как цепочка точек прервалась.
            dots = 0
            continue

        # Если символ — точка, увеличиваем счётчик подряд идущих точек.
        dots += 1
        # Когда набралось две точки подряд и в результате есть хотя бы один символ,
        # удаляем последний символ (эффект «Backspace») и обнуляем счётчик точек.
        if dots == 2 and result:
            result.pop()
            dots = 0

    # Собираем список символов обратно в строку и возвращаем её.
    return ''.join(result)


if __name__ == '__main__':
    # Этот блок выполняется, когда файл запускается как программа, а не импортируется как модуль.
    # Считываем весь входной текст из стандартного ввода (например, из консоли или файла).
    data: str = sys.stdin.read()
    # Применяем функцию decrypt к считанным данным.
    decryption: str = decrypt(data)
    # Выводим расшифрованную строку в стандартный вывод (обычно в консоль).
    print(decryption)