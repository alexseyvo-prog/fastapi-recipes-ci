import unittest
from decrypt import decrypt

# Импортируем модуль unittest, который предоставляет инфраструктуру для написания и запуска тестов.
# Импортируем функцию decrypt из основного модуля decrypt.py, чтобы проверять её работу.


class TestDecrypt(unittest.TestCase):
    """
    Класс TestDecrypt содержит набор модульных тестов для функции decrypt.
    Он наследуется от unittest.TestCase, поэтому все методы, имена которых
    начинаются с test_, воспринимаются как отдельные тесты.
    """

    def test_one_dot_cases(self):
        """
        Проверяет случаи, где в строке встречается одиночная точка.
        Логика:
        - 'абра-кадабра.' -> одиночная точка в конце, результат должен быть 'абра-кадабра';
        - '.' -> строка из одной точки, результат должен быть пустой строкой.
        """
        cases = {
            'абра-кадабра.': 'абра-кадабра',
            '.': '',
        }
        # Перебираем пары вход-ожидаемый результат и создаём под-тест для каждого случая.
        for encrypted, expected in cases.items():
            with self.subTest(encrypted=encrypted):
                # Проверяем, что decrypt(encrypted) даёт именно expected.
                self.assertEqual(decrypt(encrypted), expected)

    def test_two_dot_cases(self):
        """
        Проверяет строки, где появляются пары точек '..',
        которые должны удалять один предыдущий символ (эффект «Backspace»).
        Примеры:
        - 'абраа..-кадабра' -> лишняя 'а' удаляется, получается 'абра-кадабра';
        - 'абра--..кадабра' -> двойные точки удаляют лишний '-', получается 'абра-кадабра';
        - 'абр......a.' -> несколько пар точек очищают 'абр', остаётся 'a';
        - '1..2.3' -> '1' удаляется двойной точкой, одиночная точка остаётся, итог '23'.
        """
        cases = {
            'абраа..-кадабра': 'абра-кадабра',
            'абра--..кадабра': 'абра-кадабра',
            'абр......a.': 'a',
            '1..2.3': '23',
        }
        for encrypted, expected in cases.items():
            with self.subTest(encrypted=encrypted):
                self.assertEqual(decrypt(encrypted), expected)

    def test_three_dot_cases(self):
        """
        Проверяет комбинации, где встречается три точки подряд и более сложные случаи.
        Здесь важно, что каждые две точки удаляют символ, а оставшиеся одиночные точки
        просто учитываются, но сами ничего не удаляют.
        Примеры:
        - 'абраа..-.кадабра' -> лишняя 'а' удалена, остаётся 'абра-кадабра';
        - 'абрау...-кадабра' -> 'у' и лишний символ удаляются через последовательность точек,
          итог также 'абра-кадабра'.
        """
        cases = {
            'абраа..-.кадабра': 'абра-кадабра',
            'абрау...-кадабра': 'абра-кадабра',
        }
        for encrypted, expected in cases.items():
            with self.subTest(encrypted=encrypted):
                self.assertEqual(decrypt(encrypted), expected)

    def test_many_dots_cases(self):
        """
        Проверяет длинные последовательности точек, которые полностью очищают строку.
        Примеры:
        - 'абра........' -> несколько пар точек постепенно удаляют все буквы, результат пустой;
        - '1.......................' -> то же самое для строки, начинающейся с '1'.
        """
        cases = {
            'абра........': '',
            '1.......................': '',
        }
        for encrypted, expected in cases.items():
            with self.subTest(encrypted=encrypted):
                self.assertEqual(decrypt(encrypted), expected)


if __name__ == '__main__':
    # Этот блок запускает тесты, если файл выполняется напрямую:
    # unittest.main() находит все классы, унаследованные от unittest.TestCase,
    # и запускает все методы, начинающиеся с test_, выводя отчёт о прохождении.
    unittest.main()