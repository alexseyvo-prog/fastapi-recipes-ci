from datetime import datetime

from flask import Flask

# Создаём Flask-приложение.
# Оно будет обрабатывать HTTP-запросы и возвращать строки с приветствиями.
app = Flask(__name__)

# Кортеж приветствий по дням недели.
# Порядок элементов соответствует значению datetime.today().weekday():
# 0 — понедельник, 1 — вторник, 2 — среда, 3 — четверг, 4 — пятница,
# 5 — суббота, 6 — воскресенье.
GREETINGS = (
    'Хорошего понедельника',  # индекс 0
    'Хорошего вторника',      # индекс 1
    'Хорошей среды',          # индекс 2
    'Хорошего четверга',      # индекс 3
    'Хорошей пятницы',        # индекс 4
    'Хорошей субботы',        # индекс 5
    'Хорошего воскресенья'    # индекс 6
)


def get_weekday_greeting() -> str:
    """
    Возвращает пожелание хорошего дня в зависимости
    от текущего дня недели.

    Логика:
    - datetime.today().weekday() возвращает число от 0 до 6,
      где 0 — понедельник, а 6 — воскресенье.
    - Это число используется как индекс кортежа GREETINGS,
      поэтому выбирается правильная строка для текущего дня.
    """
    weekday: int = datetime.today().weekday()
    return GREETINGS[weekday]


@app.route('/hello-world/<name>')
def hello_world(name: str) -> str:
    """
    HTTP-роут /hello-world/<name>, который возвращает
    персональное приветствие с пожеланием хорошего дня.

    Параметры:
    - name: строка из URL, имя пользователя.

    Логика работы:
    - определяем текущий день недели через datetime.today().weekday();
    - по этому номеру берём соответствующую строку из GREETINGS;
    - формируем итоговую фразу вида:
      'Привет, {name}. {greeting}!'.

    Пример:
    - запрос /hello-world/Иван в пятницу:
      'Привет, Иван. Хорошей пятницы!'.
    - запрос /hello-world/Мария в воскресенье:
      'Привет, Мария. Хорошего воскресенья!'.
    """
    greeting: str = get_weekday_greeting()
    return f'Привет, {name}. {greeting}!'  # используем общую функцию


if __name__ == '__main__':
    # Запускаем Flask-сервер в режиме отладки.
    # debug=True включает автоматический перезапуск при изменении кода
    # и подробные сообщения об ошибках в браузере.
    app.run(debug=True)