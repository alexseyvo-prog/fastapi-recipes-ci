"""
Самопечатающийся скрипт (квазиквин).

При запуске печатает на экран ровно свой собственный текст.
Первая часть делает примерный расчёт (сумму квадратов),
вторая часть — «магический код», который выводит текст скрипта целиком.
"""

result = 0
for n in range(1, 11):
    result += n ** 2

print(f'Сумма квадратов чисел от 1 до 10 включительно = {result}\n')

# ----- % Secret magic code % -----
# Открываем текущий файл по пути __file__ и печатаем его содержимое.
# Так скрипт будет выводить себя целиком, независимо от дальнейших правок.
if __name__ == "__main__":
    with open(__file__, "r", encoding="utf-8") as f:
        source = f.read()
    print(source)